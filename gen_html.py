#!/usr/bin/env python3
"""Embed www/index.html into src/index_html.h as a C byte array."""
import os, sys

root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
src = os.path.join(root, "www", "index.html")
dst = os.path.join(root, "src", "index_html.h")

data = open(src, "rb").read()
lines = []
for i in range(0, len(data), 16):
    chunk = data[i:i + 16]
    lines.append("  " + ", ".join("0x%02x" % b for b in chunk))

with open(dst, "w") as f:
    f.write("/* generated by tools/gen_html.py - do not edit */\n")
    f.write("static const unsigned char INDEX_HTML[] = {\n")
    f.write(",\n".join(lines))
    f.write("\n};\n")
    f.write("#define INDEX_HTML_LEN %d\n" % len(data))

print("wrote", dst, len(data), "bytes")
